-- Private owner-only dashboard views. They are NOT exposed to game clients.
create schema if not exists private;

create or replace view private.lbc_stats_30d as
with visits as (
  select owner_id, count(distinct created_at::date) as visit_days
  from public.lbc_events
  where event_type='visit' and created_at >= now() - interval '30 days'
  group by owner_id
), starters as (
  select distinct owner_id
  from public.lbc_events
  where event_type='start_match' and created_at >= now() - interval '30 days'
)
select
  (select count(*) from visits) as visitors_30d,
  (select count(*) from starters) as players_started_30d,
  (select count(*) from visits where visit_days >= 2) as returning_players_30d,
  (select count(*) from public.lbc_events where event_type='start_match' and created_at >= now() - interval '30 days') as matches_started_30d,
  (select count(*) from public.lbc_events where event_type='finish_match' and created_at >= now() - interval '30 days') as matches_finished_30d,
  (select round(avg(rating)::numeric,2) from public.lbc_ratings where created_at >= now() - interval '30 days') as average_rating_30d,
  (select count(*) from public.lbc_ratings where created_at >= now() - interval '30 days') as ratings_30d;

create or replace view private.lbc_sources_30d as
select
  source,
  count(*) filter (where event_type='visit') as visits,
  count(distinct owner_id) filter (where event_type='visit') as unique_visitors,
  count(distinct owner_id) filter (where event_type='start_match') as players_started,
  count(*) filter (where event_type='start_match') as matches_started,
  count(*) filter (where event_type='finish_match') as matches_finished
from public.lbc_events
where created_at >= now() - interval '30 days'
group by source
order by players_started desc, unique_visitors desc;

revoke all on schema private from anon, authenticated;
revoke all on private.lbc_stats_30d from anon, authenticated;
revoke all on private.lbc_sources_30d from anon, authenticated;

