-- Keep updated_at fresh for online leaderboard rows.
create or replace function public.lbc_set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists lbc_room_players_updated_at on public.lbc_room_players;
create trigger lbc_room_players_updated_at
before update on public.lbc_room_players
for each row execute function public.lbc_set_updated_at();

