create table if not exists public.lbc_rooms (
  code text primary key,
  host_id uuid not null,
  max_number integer not null check (max_number in (9,12,15,18)),
  rounds integer not null check (rounds in (3,5,7)),
  status text not null default 'open' check (status in ('open','closed')),
  created_at timestamptz not null default now()
);

create table if not exists public.lbc_room_players (
  id bigint generated by default as identity primary key,
  room_code text not null references public.lbc_rooms(code) on delete cascade,
  owner_id uuid not null,
  nickname text not null check (char_length(nickname) between 1 and 24),
  progress_round integer not null default 0,
  partial_score integer not null default 0,
  total_score integer,
  finished boolean not null default false,
  started_at timestamptz,
  finished_at timestamptz,
  last_seen timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(room_code, owner_id)
);

create table if not exists public.lbc_events (
  id bigint generated by default as identity primary key,
  owner_id uuid not null,
  event_type text not null check (event_type in ('visit','start_match','finish_match')),
  source text not null default 'direct',
  box_number integer,
  rounds integer,
  total_score integer,
  language text,
  room_code text,
  created_at timestamptz not null default now()
);

create table if not exists public.lbc_ratings (
  id bigint generated by default as identity primary key,
  owner_id uuid not null,
  rating integer not null check (rating between 1 and 5),
  language text,
  source text not null default 'direct',
  created_at timestamptz not null default now()
);

create index if not exists lbc_room_players_room_idx on public.lbc_room_players(room_code);
create index if not exists lbc_events_created_idx on public.lbc_events(created_at);
create index if not exists lbc_events_owner_idx on public.lbc_events(owner_id);
create index if not exists lbc_events_type_idx on public.lbc_events(event_type);
create index if not exists lbc_ratings_created_idx on public.lbc_ratings(created_at);

alter table public.lbc_rooms enable row level security;
alter table public.lbc_room_players enable row level security;
alter table public.lbc_events enable row level security;
alter table public.lbc_ratings enable row level security;

