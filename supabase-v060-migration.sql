create extension if not exists pgcrypto;

-- 1) Player profile for the v0.6 identity.
create table if not exists public.lbc_profiles (
  owner_id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null check (char_length(trim(nickname)) between 2 and 24),
  completed_games integer not null default 0 check (completed_games >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2) Automatic Arena matchmaking queue.
create table if not exists public.lbc_arena_queue (
  owner_id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null check (char_length(trim(nickname)) between 2 and 24),
  max_number integer not null check (max_number in (9,12,15,18)),
  rounds integer not null check (rounds in (3,5,7)),
  player_count integer not null check (player_count between 2 and 6),
  persona text not null default 'friend' check (persona in ('friend','professor','provoker','comic','silent')),
  status text not null default 'queued' check (status in ('queued','matched','cancelled')),
  match_id uuid,
  joined_at timestamptz not null default now(),
  last_seen timestamptz not null default now()
);

-- 3) Arena matches. Entry fields are placeholders only; v0.6.0 runs FREE.
create table if not exists public.lbc_arena_matches (
  id uuid primary key default gen_random_uuid(),
  max_number integer not null check (max_number in (9,12,15,18)),
  rounds integer not null check (rounds in (3,5,7)),
  player_count integer not null check (player_count between 2 and 6),
  status text not null default 'playing' check (status in ('waiting','playing','finished','abandoned')),
  current_seat integer not null default 1,
  current_round integer not null default 1,
  turn_seconds integer not null check (turn_seconds between 10 and 120),
  turn_started_at timestamptz,
  entry_currency text not null default 'free' check (entry_currency in ('free','eur','pi')),
  entry_amount numeric(18,8) not null default 0 check (entry_amount >= 0),
  created_at timestamptz not null default now(),
  finished_at timestamptz
);

